/**
 * Builds the table that says which country a time zone is in:
 *
 *   npm run build:time-zones [-- <zoneinfo dir>]
 *
 * Reads the IANA time zone database installed with the system (default /usr/share/zoneinfo): `zone.tab` names the
 * country of each zone, and the links in `tzdata.zi` add the old names browsers still report ("Asia/Calcutta").
 * Writes src/core/time-zone-countries.ts, which is committed. Countries rarely change their zones; run it after a
 * tzdata release that adds one.
 */
import { readFileSync, writeFileSync } from "node:fs";
import { join } from "node:path";

const OUT = "src/core/time-zone-countries.ts";
/** Old POSIX-style names that say nothing about where the user is, though some tzdata builds link them to a zone in one country ("EST" to America/Panama). */
const NOT_A_PLACE: ReadonlySet<string> = new Set(["EST", "MST", "HST", "CET", "EET", "MET", "WET", "CST6CDT", "EST5EDT", "MST7MDT", "PST8PDT"]);

const dir = process.argv[2] ?? "/usr/share/zoneinfo";
const version = /^# version (\S+)/m.exec(readFileSync(join(dir, "tzdata.zi"), "utf8"))?.[1] ?? "unknown";

const country = new Map<string, string>();
for (const line of readFileSync(join(dir, "zone.tab"), "utf8").split("\n")) {
  if (!line || line.startsWith("#")) continue;
  const [code, , zone] = line.split("\t");
  if (code && zone) country.set(zone, code);
}

const links = readFileSync(join(dir, "tzdata.zi"), "utf8")
  .split("\n")
  .filter((l) => l.startsWith("L "))
  .map((l) => l.split(" ") as [string, string, string]);
for (const [, target, name] of links) {
  if (country.has(name) || NOT_A_PLACE.has(name)) continue;
  const code = country.get(target);
  if (code) country.set(name, code);
}

const byCountry = new Map<string, string[]>();
for (const [zone, code] of country) byCountry.set(code, [...(byCountry.get(code) ?? []), zone]);
const lines = [...byCountry]
  .sort(([a], [b]) => a.localeCompare(b))
  .map(([code, zones]) => `  ${code}: ${JSON.stringify(zones.sort().join(" "))},`);

writeFileSync(
  OUT,
  `// Generated by \`npm run build:time-zones\` from the IANA time zone database ${version}. Do not edit.

/** The time zones in each country, as ISO 3166-1 alpha-2 code → zone names separated by spaces. */
export const TIME_ZONE_COUNTRIES: Readonly<Record<string, string>> = {
${lines.join("\n")}
};
`,
);
process.stderr.write(`Wrote ${OUT}: ${country.size} time zones in ${byCountry.size} countries (tzdata ${version}).\n`);
